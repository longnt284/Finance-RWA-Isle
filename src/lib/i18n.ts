const DICTS: Record<Lang, Dict> = { vi, en };

/**
 * Hai từ điển phải phủ đúng cùng một tập khoá. Thiếu khoá nào thì bản dịch sẽ
 * lặng lẽ rơi về tiếng Việt giữa giao diện tiếng Anh — lỗi rất khó thấy khi
 * duyệt tay, nên báo ngay lúc phát triển.
 */
export function missingKeys(): { onlyVi: string[]; onlyEn: string[] } {
  const viKeys = new Set(Object.keys(vi));
  const enKeys = new Set(Object.keys(en));
  return {
    onlyVi: [...viKeys].filter((key) => !enKeys.has(key)).sort(),
    onlyEn: [...enKeys].filter((key) => !viKeys.has(key)).sort(),
  };
}

if (import.meta.env.DEV) {
  const { onlyVi, onlyEn } = missingKeys();
  if (onlyVi.length || onlyEn.length) {
    console.warn("[i18n] Từ điển lệch khoá", { thiếuTrongEn: onlyVi, thiếuTrongVi: onlyEn });
  }
}

export function makeT(lang: Lang) {
  const d = DICTS[lang];
  return function t(key: string, vars?: Record<string, string | number>): string {
    let s = d[key] ?? vi[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
  };
}

export type TFn = ReturnType<typeof makeT>;
